// Bundles migrations/*.sql into worker/schema.ts so a fresh D1 database
// can be bootstrapped automatically on first request.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
const dir = new URL("../migrations/", import.meta.url);
const sql = readdirSync(dir).filter((f) => f.endsWith(".sql")).sort().map((f) => readFileSync(new URL(f, dir), "utf8")).join("\n");
writeFileSync(new URL("../worker/schema.ts", import.meta.url), `// AUTO-GENERATED by scripts/gen-schema.mjs — do not edit.\nexport const SCHEMA_SQL = ${JSON.stringify(sql)};\n`);
console.log("worker/schema.ts written");
